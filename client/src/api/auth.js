/**
 * API: authentication endpoints, one function per endpoint (see docs/openapi.json, tag "Auth").
 * The session lives in an HttpOnly cookie that the browser sends by itself: nothing to store here.
 */
import { request } from './request.js';

// Self-registration is only for hikers: the server sets the role. Resolves to the new user.
export const register = ({ firstName, lastName, email, phone, password }) =>
  request('/auth/register', {
    method: 'POST',
    body: JSON.stringify({ firstName, lastName, email, phone, password }),
  });

// The same call for every role. Resolves to the user.
export const login = ({ email, password }) =>
  request('/auth/login', { method: 'POST', body: JSON.stringify({ email, password }) });

// Resolves to null (204).
export const logout = () => request('/auth/logout', { method: 'POST' });

// The user of the current session. Rejects with ApiError 401 when nobody is logged in.
export const getCurrentUser = () => request('/auth/me');

// The password (MH-07).

// Changes the password of the user logged in, who stays logged in. It also ends the obligation to
// change a password generated by the staff (mustChangePassword). Resolves to null (204). Rejects with
// ApiError 401 (not logged in), 400 (new password shorter than 8) or 422 (the current password is
// wrong, or the new one is the same as the current one).
export const changePassword = ({ currentPassword, newPassword }) =>
  request('/auth/change-password', { method: 'POST', body: JSON.stringify({ currentPassword, newPassword }) });

// Asks for the email with the link to choose a new password. Resolves to null (204) whether the email
// has an account or not. A new request makes the previous link stop working.
export const requestPasswordReset = (email) =>
  request('/auth/password-reset-requests', { method: 'POST', body: JSON.stringify({ email }) });

// Chooses a new password with the token of the link. It does not log in. Resolves to null (204).
// Rejects with ApiError 422 code RESET_LINK_NOT_VALID (expired, used, replaced or never existed).
export const resetPassword = ({ token, newPassword }) =>
  request('/auth/password-resets', { method: 'POST', body: JSON.stringify({ token, newPassword }) });
