-- Dietary needs and allergies of a booking (MH-05): one line per guest who has any, so at most
-- as many lines as people (checked by the server). A line has diets and allergies from the preset
-- lists of server/src/domain/dietaryNeeds.js, an "other" diet and an "other" allergy in words, and
-- other requests for the kitchen; at least one of them.
CREATE TABLE booking_requirement (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    diets TEXT[] NOT NULL DEFAULT '{}'
        CHECK (diets <@ ARRAY['VEGETARIAN', 'VEGAN', 'PESCATARIAN', 'LACTOSE_FREE']),
    other_diet TEXT CHECK (char_length(btrim(other_diet)) BETWEEN 1 AND 100),
    allergies TEXT[] NOT NULL DEFAULT '{}'
        CHECK (allergies <@ ARRAY['GLUTEN', 'MILK', 'EGGS', 'PEANUTS', 'TREE_NUTS', 'FISH', 'SHELLFISH']),
    other_allergy TEXT CHECK (char_length(btrim(other_allergy)) BETWEEN 1 AND 100),
    other_requests TEXT CHECK (char_length(btrim(other_requests)) BETWEEN 1 AND 300),
    -- The flag the kitchen reads: derived, so it can never disagree with the allergies.
    has_allergies BOOLEAN GENERATED ALWAYS AS (cardinality(allergies) > 0 OR other_allergy IS NOT NULL) STORED,
    CONSTRAINT booking_requirement_not_empty CHECK (
        cardinality(diets) > 0 OR other_diet IS NOT NULL
        OR cardinality(allergies) > 0 OR other_allergy IS NOT NULL
        OR other_requests IS NOT NULL
    )
);

CREATE INDEX booking_requirement_booking_idx ON booking_requirement (booking_id);
