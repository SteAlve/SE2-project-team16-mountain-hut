CREATE TABLE table_set (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE hut_table (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_set_id INTEGER NOT NULL REFERENCES table_set (id) ON DELETE RESTRICT,
    table_number INTEGER NOT NULL CHECK (table_number > 0),
    seat_capacity INTEGER NOT NULL CHECK (seat_capacity > 0),
    CONSTRAINT hut_table_number_unique UNIQUE (table_set_id, table_number),
    CONSTRAINT hut_table_id_set_unique UNIQUE (id, table_set_id)
);

-- Assumption pending issue #23: bookings use employee-defined slots and reserve
-- seats for the full slot interval.
-- A slot without a table set is intentionally not bookable (issue #17).
CREATE TABLE slot (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_date DATE NOT NULL,
    starts_at TIME NOT NULL,
    ends_at TIME NOT NULL,
    table_set_id INTEGER REFERENCES table_set (id) ON DELETE RESTRICT,
    CONSTRAINT slot_valid_interval CHECK (starts_at < ends_at),
    CONSTRAINT slot_unique_start UNIQUE (service_date, starts_at),
    CONSTRAINT slot_id_table_set_unique UNIQUE (id, table_set_id)
);

CREATE TABLE booking (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hiker_id INTEGER NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
    slot_id INTEGER NOT NULL,
    table_set_id INTEGER NOT NULL,
    -- Whether a hiker may make multiple bookings for one slot is still open (issue #25).
    -- party_size has no maximum until the business limit is clarified (issue #27).
    party_size INTEGER NOT NULL CHECK (party_size > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT booking_slot_table_set_fk
        FOREIGN KEY (slot_id, table_set_id)
        REFERENCES slot (id, table_set_id)
        ON DELETE RESTRICT,
    CONSTRAINT booking_id_slot_set_unique UNIQUE (id, slot_id, table_set_id)
);

CREATE INDEX booking_active_by_slot_idx
    ON booking (slot_id)
    WHERE cancelled_at IS NULL;

-- Assumption for the initial model: a table set may be referenced by multiple
-- slots. Changes to a shared set can affect every linked slot; handle such
-- changes under MH-19 while preserving existing reservations (issue #17).
-- This table stores the backend's seat assignments; it does not define the
-- allocation algorithm, whose precise preference order is still open (issue #18).
CREATE TABLE booking_table (
    booking_id INTEGER NOT NULL,
    slot_id INTEGER NOT NULL,
    table_set_id INTEGER NOT NULL,
    hut_table_id INTEGER NOT NULL,
    seat_count INTEGER NOT NULL CHECK (seat_count > 0),
    PRIMARY KEY (booking_id, hut_table_id),
    FOREIGN KEY (booking_id, slot_id, table_set_id)
        REFERENCES booking (id, slot_id, table_set_id)
        ON DELETE CASCADE,
    FOREIGN KEY (hut_table_id, table_set_id)
        REFERENCES hut_table (id, table_set_id)
        ON DELETE RESTRICT
);

CREATE INDEX booking_table_by_slot_table_idx
    ON booking_table (slot_id, hut_table_id);

-- A hiker has one booking per time slot (a cancelled booking does not count).
CREATE UNIQUE INDEX booking_one_active_per_hiker_slot_idx
  ON booking (hiker_id, slot_id)
  WHERE cancelled_at IS NULL;
