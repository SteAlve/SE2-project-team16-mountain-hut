-- MH-20: the hikes that a hiker registers before leaving, so that the hut has the information if the
-- hiker does not come back as expected (product owner: SE2-Polito/AY26-27-Mountain-Hut#49 and #51).
--
-- A hike has a destination (a name), a route (a text description) and the passage points in between,
-- which can be none and are kept in the order of the route. The departure and the expected return are
-- instants: the API gives them as the local time of the hut and the server turns them with the time
-- zone of the hut, so the later stories (the overdue hikes, MH-24) compare them with the clock.
-- The start is always the hut, so it is not stored.
--
-- A hike is considered started at its departure time, and a hiker who does not leave declares it
-- finished (#53): there is no status here, the later stories add what they need.

-- Lets the database compare the hiker (an integer) in the same rule as the times.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE hike (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hiker_id INTEGER NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
    destination TEXT NOT NULL CHECK (char_length(btrim(destination)) BETWEEN 1 AND 100),
    route TEXT NOT NULL CHECK (char_length(btrim(route)) BETWEEN 1 AND 500),
    -- The text of each point is checked by the server (1 to 100 characters, one line).
    passage_points TEXT[] NOT NULL DEFAULT '{}' CHECK (cardinality(passage_points) <= 100),
    departure_at TIMESTAMPTZ NOT NULL,
    return_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT hike_return_after_departure CHECK (return_at > departure_at),
    -- Two hikes of the same hiker cannot overlap in time. One that starts when the other ends is fine.
    -- The database decides, so two requests at the same time cannot both be saved.
    CONSTRAINT hike_no_overlap
        EXCLUDE USING gist (hiker_id WITH =, tstzrange(departure_at, return_at, '[)') WITH &&)
);

-- "My hikes": the hikes of a hiker in order of departure.
CREATE INDEX hike_by_hiker_idx ON hike (hiker_id, departure_at);
